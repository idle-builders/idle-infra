#!/usr/bin/env python3
"""Generate MCP tool definitions from docs/api/console-v1.yaml.

Every operation marked `x-variants: [..., agent]` becomes one MCP tool, named by
its `x-mcp.tool`. The generated Go file is data only: the MCP server dispatches
each tool through the same HTTP handler the browser console uses, so the two
adapters cannot drift apart.

    python3 scripts/gen-mcp-tools.py docs/api/console-v1.yaml \
        docker/infra-console/internal/mcp/tools_gen.go

Run via scripts/gen-console.sh; the output is committed and CI fails if
regenerating changes it.
"""

import json
import sys

try:
    import yaml
except ImportError:  # pragma: no cover
    print("PyYAML is required", file=sys.stderr)
    sys.exit(1)

HEADER = '''// Code generated by scripts/gen-mcp-tools.py from docs/api/console-v1.yaml.
// DO NOT EDIT.
//
// One entry per operation marked `agent` in the contract's x-variants. The MCP
// server dispatches each through the same HTTP handler the console uses, so a
// tool cannot diverge from the endpoint it exposes.

package mcp

// Tool is a generated MCP tool bound to one contract operation.
type Tool struct {
\tName        string
\tDescription string
\t// Path is the operation's template, e.g. /projects/{project}/deployments.
\tPath        string
\tPathParams  []string
\tQueryParams []string
\t// InputSchema is the JSON Schema advertised to clients, as raw JSON.
\tInputSchema string
}

// Tools is every agent-variant operation in the contract.
var Tools = []Tool{
'''


def schema_for(spec, param):
    """Resolve a parameter reference and return (name, location, json schema)."""
    if "$ref" in param:
        ref = param["$ref"]
        cur = spec
        for part in ref.lstrip("#/").split("/"):
            cur = cur[part]
        param = cur
    return param.get("name"), param.get("in"), param.get("schema") or {}


def resolve(spec, ref):
    cur = spec
    for part in ref.lstrip("#/").split("/"):
        if not isinstance(cur, dict) or part not in cur:
            raise KeyError("unresolvable $ref: %s" % ref)
        cur = cur[part]
    return cur


def clean(schema, spec, seen=()):
    """Inline $refs and strip keys that are noise in a tool schema.

    An MCP tool schema is standalone: there is no components document for a
    client to resolve against, and the SDK rejects a dangling pointer outright.
    So every local $ref is expanded here rather than passed through.
    """
    if not isinstance(schema, dict):
        return schema

    ref = schema.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/"):
        if ref in seen:
            # A recursive schema cannot be inlined; fall back to an open object
            # rather than looping forever.
            return {"type": "object"}
        target = clean(resolve(spec, ref), spec, seen + (ref,))
        # Sibling keys alongside $ref (a description, usually) win.
        rest = {k: v for k, v in schema.items() if k != "$ref"}
        merged = dict(target)
        merged.update(clean(rest, spec, seen))
        return merged

    out = {}
    for key, value in schema.items():
        if key in ("example", "examples", "x-mcp", "x-variants"):
            continue
        if isinstance(value, dict):
            out[key] = clean(value, spec, seen)
        elif isinstance(value, list):
            out[key] = [clean(v, spec, seen) for v in value]
        else:
            out[key] = value
    return out


def go_string(value):
    return json.dumps(value)


def go_slice(values):
    if not values:
        return "nil"
    return "[]string{" + ", ".join(go_string(v) for v in values) + "}"


def main(argv):
    if len(argv) != 3:
        print("usage: gen-mcp-tools.py <spec.yaml> <output.go>", file=sys.stderr)
        return 1
    spec_path, out_path = argv[1], argv[2]

    with open(spec_path, encoding="utf-8") as handle:
        spec = yaml.safe_load(handle)

    lines = [HEADER]
    count = 0

    for path, item in (spec.get("paths") or {}).items():
        shared = item.get("parameters") or []
        for method, op in (item or {}).items():
            if method not in ("get",):
                continue
            variants = op.get("x-variants") or []
            if "agent" not in variants:
                continue

            tool = (op.get("x-mcp") or {}).get("tool")
            if not tool:
                print("no x-mcp.tool for %s %s" % (method, path), file=sys.stderr)
                return 1

            properties = {}
            required = []
            path_params = []
            query_params = []

            for param in shared + (op.get("parameters") or []):
                name, location, schema = schema_for(spec, param)
                if not name:
                    continue
                # Follow the $ref. Discarding it dropped the description of
                # every shared parameter, so every project-scoped tool
                # advertised `project` as a bare regex with no explanation of
                # what it is or that non-tenant namespaces are refused.
                resolved = resolve(spec, param["$ref"]) if "$ref" in param else param
                description = (resolved.get("description") or "").strip()

                entry = clean(schema, spec)
                if description:
                    entry["description"] = description.split("\n\n")[0].replace("\n", " ").strip()
                properties[name] = entry

                if location == "path":
                    path_params.append(name)
                    required.append(name)
                elif location == "query":
                    query_params.append(name)
                    if param.get("required"):
                        required.append(name)

            input_schema = {"type": "object", "properties": properties}
            if required:
                input_schema["required"] = sorted(set(required))

            description = (op.get("summary") or tool).strip()
            detail = (op.get("description") or "").strip()
            if detail:
                # First paragraph only: an MCP tool list is read by a model with
                # a budget, not rendered as documentation.
                first = detail.split("\n\n")[0].replace("\n", " ").strip()
                description = "%s. %s" % (description.rstrip("."), first)

            lines.append("\t{\n")
            lines.append("\t\tName:        %s,\n" % go_string(tool))
            lines.append("\t\tDescription: %s,\n" % go_string(description))
            lines.append("\t\tPath:        %s,\n" % go_string(path))
            lines.append("\t\tPathParams:  %s,\n" % go_slice(path_params))
            lines.append("\t\tQueryParams: %s,\n" % go_slice(query_params))
            lines.append("\t\tInputSchema: %s,\n" % go_string(
                json.dumps(input_schema, sort_keys=True, separators=(",", ":"))))
            lines.append("\t},\n")
            count += 1

    lines.append("}\n")

    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("".join(lines))

    print("generated %d MCP tools -> %s" % (count, out_path))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
